def style_header(ws, n):
    for c in range(1, n + 1):
        cell = ws.cell(row=1, column=c)
        cell.fill = HDR_FILL; cell.font = HDR_FONT
        cell.alignment = Alignment(wrap_text=True, vertical="center", horizontal="left")
        cell.border = BORDER
    ws.row_dimensions[1].height = 32
    ws.freeze_panes = "A2"

def style_body(ws, n, level_col=None):
    for row in ws.iter_rows(min_row=2, max_col=n):
        for cell in row:
            cell.font = BODY_FONT; cell.alignment = WRAP; cell.border = BORDER
        if level_col is not None:
            lvl = ws.cell(row=row[0].row, column=level_col).value
            fill = {-2: L_NEG, -1: L_BASE, 0: L_STRONG}.get(lvl)
            if fill:
                for cell in row:
                    cell.fill = fill

def widths(ws, ws_widths):
    for i, w in enumerate(ws_widths, 1):
        ws.column_dimensions[get_column_letter(i)].width = w

